---(seconds since epoch). Pass it to `date()` for formatting, or compare it against
---`time()` to derive a relative age.
---@return number timestamp Unix timestamp (seconds since epoch, UTC).
function MountsRarity:GetLastUpdated()
  return LAST_UPDATED
end

